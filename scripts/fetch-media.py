#!/usr/bin/env python3
"""fetch-media.py — 多平台媒體下載（影片 / 圖片自動判斷）

配合 DSH Edge Assistant：
  - cookie：自動用「目前在 Edge 開著的分頁」或既有 data/cookies/<host>.txt
  - 影片：交給 yt-dlp（bilibili / YouTube / X …）
  - 圖片：Pixiv 走官方 ajax 取原圖；其他網站開頁後用 page.images 抓大圖
  - 自動判斷：先看平台，再試 yt-dlp，不行就退回圖片模式

用法：
  python scripts\\fetch-media.py <url>
  python scripts\\fetch-media.py <url> --mode video
  python scripts\\fetch-media.py <url> --mode image --out D:\\pics
  python scripts\\fetch-media.py <url> --dry-run          # 只判斷/列出，不下載
  python scripts\\fetch-media.py <url> --cookie-host example.com
  python scripts\\fetch-media.py <url> --max-images 30 --keep-tab

需要：
  - bridge（127.0.0.1:8765）在跑，Edge 開著（拿 cookie / 開頁用）
  - yt-dlp（影片模式）、ffmpeg（合併音視訊）
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))

try:
    import bridge as bridge_cli  # noqa: E402  (server/bridge.py)
except Exception as e:  # pragma: no cover
    print("無法載入 server/bridge.py：%s" % e, file=sys.stderr)
    raise SystemExit(2)

BRIDGE = "http://127.0.0.1:8765"
UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/156.0.0.0 Safari/537.36 Edg/156.0.0.0"
)
SAFE = re.compile(r"[^A-Za-z0-9._-]+")

# 下載內容的歸類根目錄；DSH_MEDIA_ROOT 環境變數可覆寫
DEFAULT_MEDIA_ROOT = r"D:\剪輯\DSH Edge Assistant"
PLATFORM_NAMES = {
    "www.pixiv.net": "pixiv",
    "pixiv.net": "pixiv",
    "x.com": "x",
    "twitter.com": "x",
    "www.twitter.com": "x",
    "youtube.com": "youtube",
    "www.youtube.com": "youtube",
    "m.youtube.com": "youtube",
    "youtu.be": "youtube",
    "bilibili.com": "bilibili",
    "www.bilibili.com": "bilibili",
    "m.bilibili.com": "bilibili",
}


def media_root():
    root = Path(os.environ.get("DSH_MEDIA_ROOT", DEFAULT_MEDIA_ROOT))
    if not root.parent.exists():
        # 沒有那個槽（換機/外接碟沒插）→ 退回專案內的 downloads
        return ROOT / "downloads"
    return root


def platform_name(host):
    return PLATFORM_NAMES.get((host or "").lower(), safe_name(host))



def log(msg):
    print(msg, flush=True)


def configure_stdio():
    """被管線/agent 擷取時用 UTF-8，終端則保留系統編碼但不再因 emoji 崩潰。"""
    for stream in (sys.stdout, sys.stderr):
        if stream is None:
            continue
        try:
            if stream.isatty():
                stream.reconfigure(errors="replace")
            else:
                stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass


def safe_name(s, limit=120):
    s = SAFE.sub("_", str(s or "unknown")).strip("_")
    return (s or "unknown")[:limit]


# ---------------- bridge ----------------

def bridge_running():
    try:
        code, body = bridge_cli.http("/health", timeout=4)
        info = json.loads(body)
        return bool(info.get("ok") or info.get("status") == "ok"), info
    except Exception:
        return False, {}


def bridge_cmd(method, args=None, timeout=60):
    return bridge_cli.cmd(method, args or {}, timeout=timeout)


def host_of(url):
    return (urllib.parse.urlparse(url).hostname or "").lower()


def active_tab():
    try:
        return bridge_cli.cmd("tabs.active")
    except SystemExit:
        return None


def open_tab(url, keep_tab=False):
    """開頁並回傳 tabId；原本就開著同一個 URL 就重用。"""
    tab = active_tab()
    if tab and (tab.get("url") or "").startswith(url[:80]):
        return tab.get("id"), False
    data = bridge_cli.cmd("tabs.open", {"url": url}, timeout=40)
    return data.get("id"), True


# ---------------- cookie ----------------

def cookie_host_for(url, override=None):
    if override:
        return bridge_cli.normalize_host(override)
    host = host_of(url)
    return bridge_cli.normalize_host(host)


def ensure_cookie_file(host):
    """拿目前的 cookie 寫成 Netscape 檔；Edge 沒開就退回既有檔案。"""
    if not host:
        return None
    path = ROOT / "data" / "cookies" / (safe_name(host) + ".txt")
    ok, info = bridge_running()
    has_client = bool((info or {}).get("clients"))
    cookies = []
    if has_client:
        try:
            cookies = bridge_cli.collect_cookies(host)
        except SystemExit:
            cookies = []
    if cookies:
        path.parent.mkdir(parents=True, exist_ok=True)
        write_netscape(cookies, path)
        log("cookie: %s（%d 個，來自 Edge）" % (host, len(cookies)))
        return path
    if path.exists():
        log("cookie: %s（沿用既有檔案）" % host)
        return path
    log("cookie: %s（沒有，可能影響需要登入的內容）" % host)
    return None


def write_netscape(cookies, path):
    lines = ["# Netscape HTTP Cookie File", "# Generated by fetch-media.py", ""]
    for c in cookies:
        domain = c.get("domain") or ""
        lines.append(
            "\t".join(
                [
                    domain,
                    "TRUE" if domain.startswith(".") else "FALSE",
                    c.get("path") or "/",
                    "TRUE" if c.get("secure") else "FALSE",
                    str(int(c.get("expirationDate") or 0)),
                    c.get("name") or "",
                    c.get("value") or "",
                ]
            )
        )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cookie_header(host):
    """組 Cookie header（給圖片下載用）。"""
    path = ROOT / "data" / "cookies" / (safe_name(host) + ".txt")
    if not path.exists():
        return ""
    pairs = []
    try:
        for line in path.read_text(encoding="utf-8").splitlines():
            if not line or line.startswith("#"):
                continue
            parts = line.split("\t")
            if len(parts) >= 7 and parts[5]:
                pairs.append(parts[5] + "=" + parts[6])
    except Exception:
        return ""
    return "; ".join(pairs)


# ---------------- http ----------------

def http_get(url, referer=None, host_for_cookie=None, timeout=60):
    headers = {"User-Agent": UA, "Accept": "*/*"}
    if referer:
        headers["Referer"] = referer
    if host_for_cookie:
        ck = cookie_header(host_for_cookie)
        if ck:
            headers["Cookie"] = ck
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read(), r.headers.get("Content-Type", "")


def download_file(url, out_path, referer=None, host_for_cookie=None):
    data, ctype = http_get(url, referer=referer, host_for_cookie=host_for_cookie)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_bytes(data)
    return out_path, len(data), ctype


# ---------------- yt-dlp ----------------

def which_ytdlp():
    found = shutil.which("yt-dlp") or shutil.which("yt-dlp.exe")
    if found:
        return found
    cand = Path(os.environ.get("LOCALAPPDATA", "")) / "Microsoft" / "WinGet" / "Packages"
    if cand.is_dir():
        for p in cand.rglob("yt-dlp.exe"):
            return str(p)
    return None


def ytdlp_can(url, cookie_file):
    yt = which_ytdlp()
    if not yt:
        return False, "找不到 yt-dlp"
    cmd = [yt, "--no-playlist", "--simulate", "--no-warnings", "--print", "%(id)s"]
    if cookie_file:
        cmd += ["--cookies", str(cookie_file)]
    cmd.append(url)
    try:
        p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                           errors="replace", timeout=90)
    except subprocess.TimeoutExpired:
        return False, "yt-dlp 探測逾時"
    if p.returncode == 0 and (p.stdout or "").strip():
        return True, ""
    tail = (p.stderr or p.stdout or "").strip().splitlines()
    return False, (tail[-1] if tail else "yt-dlp 不支援")


def ytdlp_download(url, out_dir, cookie_file, extra_args=None):
    yt = which_ytdlp()
    if not yt:
        return False, "找不到 yt-dlp（請安裝）"
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [
        yt,
        "--no-playlist",
        "--merge-output-format",
        "mp4",
        "-o",
        str(out_dir / "%(uploader_id)s - %(title).80s [%(id)s].%(ext)s"),
    ]
    if cookie_file:
        cmd += ["--cookies", str(cookie_file)]
    cmd += (extra_args or [])
    cmd.append(url)
    log("yt-dlp: " + " ".join(cmd[:2]) + " …")
    p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8",
                       errors="replace", timeout=900)
    out = (p.stdout or "") + (p.stderr or "")
    if p.returncode != 0:
        tail = out.strip().splitlines()[-3:]
        return False, " | ".join(tail)
    return True, ""


# ---------------- 圖片：Pixiv ----------------

def pixiv_illust_id(url):
    m = re.search(r"/artworks/(\d+)", url)
    return m.group(1) if m else None


def pixiv_download(url, out_dir, dry_run=False):
    illust_id = pixiv_illust_id(url)
    if not illust_id:
        return False, "無法從網址取得作品 ID", []
    log("Pixiv: 作品 %s" % illust_id)
    ajax = "https://www.pixiv.net/ajax/illust/%s" % illust_id
    try:
        raw, _ = http_get(ajax, referer="https://www.pixiv.net/", host_for_cookie="www.pixiv.net")
        body = json.loads(raw.decode("utf-8"))
    except Exception as e:
        return False, "Pixiv ajax 失敗：%s" % e, []
    if body.get("error"):
        return False, "Pixiv 回應錯誤：%s" % body.get("message"), []
    b = body.get("body") or {}
    original = (b.get("urls") or {}).get("original") or ""
    page_count = int(b.get("pageCount") or 1)
    title = b.get("title") or illust_id
    user = b.get("userName") or ""
    log("  標題：%s（%s，%d 頁）" % (title, user, page_count))
    files = []
    if dry_run:
        log("  原圖：%s" % original)
        return True, "dry-run", []
    for i in range(page_count):
        page_url = re.sub(r"_p\d+", "_p%d" % i, original)
        if not page_url:
            continue
        ext = page_url.rsplit(".", 1)[-1].split("?")[0] or "jpg"
        out_path = out_dir / ("%s_p%d.%s" % (illust_id, i, ext))
        try:
            p, size, _ = download_file(
                page_url,
                out_path,
                referer="https://www.pixiv.net/",
                host_for_cookie="www.pixiv.net",
            )
            files.append(p)
            log("  saved %s (%.2f MB)" % (p.name, size / 1_048_576))
        except urllib.error.HTTPError as e:
            return False, "第 %d 頁 HTTP %s（可能需要登入或 Referer）" % (i, e.code), files
        except Exception as e:
            return False, "第 %d 頁失敗：%s" % (i, e), files
    return True, "", files


# ---------------- 圖片：通用網頁 ----------------

def generic_images(url, out_dir, max_images=20, keep_tab=False, dry_run=False):
    host = host_of(url)
    try:
        tab_id, opened = open_tab(url, keep_tab)
    except SystemExit as e:
        return False, "bridge/Edge 不可用（%s）" % e, []
    log("頁面分頁：%s" % tab_id)
    time.sleep(4)
    try:
        data = bridge_cli.cmd("page.images", {"tabId": tab_id, "limit": max_images * 3})
    except SystemExit as e:
        return False, "讀取頁面圖片失敗：%s" % e, []
    images = data.get("images") or []
    picked = []
    seen = set()
    for img in images:
        src = (img.get("src") or "").strip()
        if not src.startswith("http"):
            continue
        if img.get("w", 0) < 300 or img.get("h", 0) < 300:
            continue
        src = re.sub(r"(?<=[?&])name=(small|medium|thumb)(?=&|$)", "name=orig", src)
        if src in seen:
            continue
        seen.add(src)
        picked.append(img)
        if len(picked) >= max_images:
            break
    log("找到 %d 張大圖（候選 %d）" % (len(picked), len(images)))
    if dry_run:
        for img in picked:
            log("  %sx%s %s" % (img.get("w"), img.get("h"), img.get("src")))
        if not keep_tab and opened:
            try:
                bridge_cli.cmd("tabs.close", {"tabId": tab_id})
            except SystemExit:
                pass
        return True, "dry-run", []
    files = []
    for i, img in enumerate(picked):
        src = re.sub(r"(?<=[?&])name=(small|medium|thumb)(?=&|$)", "name=orig", img["src"])
        ext = (re.sub(r"[?#].*$", "", src).rsplit(".", 1)[-1] or "jpg").lower()
        if ext not in ("jpg", "jpeg", "png", "gif", "webp", "avif"):
            ext = "jpg"
        out_path = out_dir / ("%s_img%02d.%s" % (safe_name(host), i, ext))
        try:
            p, size, _ = download_file(src, out_path, referer=url, host_for_cookie=host)
            files.append(p)
            log("  saved %s (%.2f MB)" % (p.name, size / 1_048_576))
        except Exception as e:
            log("  skip %s：%s" % (src[:70], e))
    if not keep_tab and opened:
        try:
            bridge_cli.cmd("tabs.close", {"tabId": tab_id})
        except SystemExit:
            pass
    return bool(files), "" if files else "沒有下載到圖片", files


# ---------------- 主流程 ----------------

def clean_url(url):
    """去掉追蹤參數（x.com?s=20、bilibili?share_source...）。"""
    p = urllib.parse.urlsplit(url)
    q = urllib.parse.parse_qs(p.query)
    keep = {k: v for k, v in q.items() if k in ("v", "list", "t", "si")}
    query = urllib.parse.urlencode(keep, doseq=True)
    return urllib.parse.urlunsplit((p.scheme, p.netloc, p.path, query, ""))


def main():
    configure_stdio()
    ap = argparse.ArgumentParser(description="多平台媒體下載（影片/圖片自動）")
    ap.add_argument("url")
    ap.add_argument("--mode", choices=["auto", "video", "image"], default="auto")
    ap.add_argument("--out", default=None, help="輸出資料夾（預設 downloads/<平台>）")
    ap.add_argument("--cookie-host", default=None, help="用哪個網域的 cookie（預設從 URL 推導）")
    ap.add_argument("--max-images", type=int, default=20)
    ap.add_argument("--keep-tab", action="store_true", help="不要關掉為了抓圖而開的分頁")
    ap.add_argument("--dry-run", action="store_true", help="只判斷/列出，不下載")
    ap.add_argument("--extra", default="", help="額外傳給 yt-dlp 的參數（空白分隔）")
    args = ap.parse_args()

    url = clean_url(args.url.strip())
    host = host_of(url)
    cookie_host = cookie_host_for(url, args.cookie_host)
    log("目標：%s（host=%s）" % (url, host))

    ok, info = bridge_running()
    if not ok:
        log("⚠ bridge（127.0.0.1:8765）沒在跑；cookie 只能用既有檔案，圖片模式不可用")
    else:
        clients = info.get("clients") or []
        log("bridge: ok（%d 個瀏覽器連線）" % len(clients))

    cookie_file = None
    if ok:
        cookie_file = ensure_cookie_file(cookie_host)
    else:
        fallback = ROOT / "data" / "cookies" / (safe_name(cookie_host) + ".txt")
        cookie_file = fallback if fallback.exists() else None
        log("cookie 檔：%s" % (cookie_file or "無"))

    mode = args.mode

    # 平台特判
    if mode == "auto" and ("pixiv.net" in host or "pixiv" in host):
        mode = "image"
        log("判斷：pixiv → 圖片模式")
    elif mode == "auto":
        if not which_ytdlp():
            mode = "image"
            log("判斷：沒有 yt-dlp → 圖片模式")
        else:
            log("判斷：先試 yt-dlp…")
            can, why = ytdlp_can(url, cookie_file)
            if can:
                mode = "video"
                log("判斷：yt-dlp 支援 → 影片模式")
            else:
                mode = "image"
                log("判斷：yt-dlp 不支援（%s）→ 圖片模式" % why)

    if args.out:
        out_dir = Path(args.out)
    else:
        kind = "影片" if mode == "video" else "圖片"
        out_dir = media_root() / kind / platform_name(host)
    log("輸出：%s" % out_dir)

    started = time.time()
    if mode == "video":
        if args.dry_run:
            can, why = ytdlp_can(url, cookie_file)
            log("dry-run：yt-dlp %s" % ("支援" if can else "不支援：" + why))
            return 0 if can else 1
        ok, err = ytdlp_download(url, out_dir, cookie_file,
                                 extra_args=args.extra.split() if args.extra else None)
        if not ok:
            log("下載失敗：%s" % err)
            return 1
        files = sorted(out_dir.glob("*"), key=lambda p: p.stat().st_mtime, reverse=True)[:5]
    else:
        if "pixiv.net" in host:
            ok, err, files = pixiv_download(url, out_dir, dry_run=args.dry_run)
        else:
            ok, err, files = generic_images(
                url, out_dir, max_images=args.max_images,
                keep_tab=args.keep_tab, dry_run=args.dry_run,
            )
        if not ok:
            log("失敗：%s" % err)
            return 1

    log("\n完成（%.1fs）" % (time.time() - started))
    if args.dry_run:
        log("dry-run：沒有下載檔案")
        return 0
    total = 0
    for f in files:
        if f and Path(f).exists() and Path(f).is_file():
            size = Path(f).stat().st_size
            total += size
            log("  %s（%.2f MB）" % (Path(f), size / 1_048_576))
    log("合計 %.2f MB → %s" % (total / 1_048_576, out_dir))
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        raise SystemExit(130)
