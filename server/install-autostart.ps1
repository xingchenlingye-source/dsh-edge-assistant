<#
  DSH Bridge — 登入時自動在背景啟動（無視窗、掛掉自動重開）

  安裝（預設放「啟動」資料夾，不需要管理員權限）：
    powershell -ExecutionPolicy Bypass -File .\install-autostart.ps1
  改用工作排程器（部分電腦需要管理員權限）：
    powershell -ExecutionPolicy Bypass -File .\install-autostart.ps1 -UseScheduledTask
  移除：
    powershell -ExecutionPolicy Bypass -File .\install-autostart.ps1 -Remove

  原理：登入後用 pythonw 啟動 bridge_daemon.py（無視窗），
  由它確保 bridge_server.py 常駐在 127.0.0.1:8765。
#>
param([switch]$Remove, [switch]$UseScheduledTask)

$ErrorActionPreference = "Stop"
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
$taskName = "DSH Bridge Server"
$startupNames = @("DSH Bridge Server.vbs", "DSH Bridge Server.lnk", "DSH Bridge Server.cmd")
$startup = [Environment]::GetFolderPath("Startup")

function Find-Python([string]$exeName) {
    $cands = @(
        (Join-Path $env:USERPROFILE ".dsh\dsh-runtimes\dsh-primary-runtime\dependencies\python\$exeName"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python312\$exeName"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python311\$exeName"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python310\$exeName")
    )
    foreach ($c in $cands) {
        if ($c -and (Test-Path $c)) { return $c }
    }
    $cmd = Get-Command $exeName -ErrorAction SilentlyContinue
    if (-not $cmd) { $cmd = Get-Command ($exeName -replace 'w\.exe$', '.exe') -ErrorAction SilentlyContinue }
    if ($cmd) { return $cmd.Source }
    return $null
}

function Remove-StartupEntry {
    foreach ($f in $startupNames) {
        $p = Join-Path $startup $f
        if (Test-Path $p) { Remove-Item $p -Force -ErrorAction SilentlyContinue }
    }
}

if ($Remove) {
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue
    Remove-StartupEntry
    Write-Host "已移除自動啟動（$taskName / 啟動資料夾）。"
    Write-Host "bridge 進程若還在跑，可用：powershell -File .\ensure-bridge.ps1 -Restart"
    exit 0
}

$pythonw = Find-Python "pythonw.exe"
if (-not $pythonw) { $pythonw = Find-Python "python.exe" }
if (-not $pythonw) {
    Write-Error "找不到 python / pythonw，請先安裝 Python 3。"
}
$daemonScript = Join-Path $here "bridge_daemon.py"
if (-not (Test-Path $daemonScript)) { Write-Error "找不到 $daemonScript" }

Remove-StartupEntry

$installed = $null
if ($UseScheduledTask) {
    try {
        $action = New-ScheduledTaskAction -Execute $pythonw -Argument ('"' + $daemonScript + '"') -WorkingDirectory $here
        $trigger = New-ScheduledTaskTrigger -AtLogOn
        $settings = New-ScheduledTaskSettingsSet `
            -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
            -ExecutionTimeLimit ([TimeSpan]::Zero) `
            -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) `
            -MultipleInstances IgnoreNew
        Unregister-ScheduledTask -TaskName $taskName -Confirm:$false -ErrorAction SilentlyContinue
        Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings `
            -Description "DSH Edge Assistant 的本機 bridge（127.0.0.1:8765），登入後常駐" `
            -Force -ErrorAction Stop | Out-Null
        $installed = "task"
        Write-Host "已安裝：工作排程器 -> $taskName（登入後自動常駐）"
    } catch {
        Write-Warning "建立工作排程失敗（$($_.Exception.Message)），改用「啟動」資料夾。"
    }
}

if (-not $installed) {
    $vbs = Join-Path $startup "DSH Bridge Server.vbs"
    $q = 'Chr(34)'
    $content = @"
' Generated by edge-dsh-bridge/install-autostart.ps1
' Starts the DSH Bridge daemon (127.0.0.1:8765) in the background at logon.
CreateObject("WScript.Shell").Run $q & "$pythonw" & $q & " " & $q & "$daemonScript" & $q, 0, False
"@
    [IO.File]::WriteAllText($vbs, $content, (New-Object Text.UTF8Encoding($false)))
    Write-Host "已安裝：啟動資料夾 -> $vbs"
}

# 立刻啟動一次，現在就能用
& (Join-Path $here "ensure-bridge.ps1")
