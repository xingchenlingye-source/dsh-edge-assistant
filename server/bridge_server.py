#!/usr/bin/env python3
"""DSH Bridge v2 — Edge 全能助手（HTTP + WebSocket 雙向通道）。

只綁定 127.0.0.1。

架構：
  Edge 擴充  ──WS /ws──►  bridge（本檔）  ◄──HTTP /cmd──   agent / CLI
      ▲                        │
      └──── cmd / result ──────┘（WebSocket JSON 訊息）

HTTP 端點：
  GET  /health                  健康狀態 + 已連線的瀏覽器
  GET  /clients                 已連線的瀏覽器清單
  POST /cmd                     送出指令並等待結果（預設 25s 逾時）
  POST /cookies                 接收 cookie（舊版相容）
  GET  /cookies/<host>          取 Netscape cookies.txt
  GET  /cookies/<host>?format=json
  GET  /domains
  GET  /screenshots/<file>      取回截圖

WebSocket 訊息：
  client → server : {"type":"hello","clientId","version","control"}
                    {"type":"ping"}
                    {"type":"result","id","ok","data"|"error"}
                    {"type":"state","control","activeTab"}
  server → client : {"type":"welcome","clientId"}
                    {"type":"cmd","id","method","args"}

指令集見 README。
"""

import argparse
import asyncio
import base64
import json
import os
import re
import sys
import time
import uuid

from aiohttp import WSMsgType, web

BASE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(BASE)
DATA_DIR = os.path.join(ROOT, "data")
COOKIE_DIR = os.path.join(DATA_DIR, "cookies")
SHOT_DIR = os.path.join(DATA_DIR, "screenshots")
LOG_PATH = None


def configure_stdio():
    """輸出編碼保護：被重導向時用 UTF-8，終端則保留系統編碼但不再因 emoji 崩潰。"""
    for stream in (sys.stdout, sys.stderr):
        if stream is None:
            continue
        try:
            if stream.isatty():
                stream.reconfigure(errors="replace")
            else:
                stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:
            pass


def log(msg):
    """同時寫 stdout（若有）與資料目錄的 bridge.log，方便常駐時追查。"""
    text = str(msg)
    try:
        print(text)
    except Exception:
        pass
    if LOG_PATH:
        try:
            os.makedirs(os.path.dirname(LOG_PATH), exist_ok=True)
            with open(LOG_PATH, "a", encoding="utf-8", errors="replace") as f:
                f.write(time.strftime("[%Y-%m-%d %H:%M:%S] ") + text + "\n")
        except Exception:
            pass


def trim_log(max_bytes=2 * 1024 * 1024):
    """log 超過 2MB 就砍掉前半，避免無限長大。"""
    try:
        if LOG_PATH and os.path.exists(LOG_PATH) and os.path.getsize(LOG_PATH) > max_bytes:
            with open(LOG_PATH, "r", encoding="utf-8", errors="replace") as f:
                data = f.read()
            with open(LOG_PATH, "w", encoding="utf-8") as f:
                f.write(data[len(data) // 2:])
    except Exception:
        pass

SAFE = re.compile(r"[^A-Za-z0-9._-]+")
CORS = {
    "Access-Control-Allow-Origin": "*",
    "Access-Control-Allow-Methods": "GET, POST, OPTIONS",
    "Access-Control-Allow-Headers": "Content-Type",
    "Cache-Control": "no-store",
}

clients = {}   # clientId -> Client
pending = {}   # cmdId -> (asyncio.Future, clientId)


class Client:
    def __init__(self, ws):
        self.ws = ws
        self.id = None
        self.version = ""
        self.control = False
        self.active = {}
        self.connected = time.time()

    def summary(self):
        return {
            "id": self.id,
            "version": self.version,
            "control": self.control,
            "activeTab": self.active,
            "connectedAt": int(self.connected),
        }


# ---------------- helpers ----------------

def safe_name(hostname: str) -> str:
    host = (hostname or "unknown").lower().lstrip(".")
    return (SAFE.sub("_", host) or "unknown")[:120]


def to_netscape(cookies) -> str:
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by DSH Bridge",
        "# " + time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "",
    ]
    for c in cookies:
        domain = c.get("domain") or ""
        lines.append(
            "\t".join(
                [
                    domain,
                    "TRUE" if domain.startswith(".") else "FALSE",
                    c.get("path") or "/",
                    "TRUE" if c.get("secure") else "FALSE",
                    str(int(c.get("expirationDate") or 0)),
                    c.get("name") or "",
                    c.get("value") or "",
                ]
            )
        )
    return "\n".join(lines) + "\n"


def save_cookies(payload):
    cookies = payload.get("cookies") or []
    host = safe_name(payload.get("hostname") or "unknown")
    os.makedirs(COOKIE_DIR, exist_ok=True)
    txt_path = os.path.join(COOKIE_DIR, host + ".txt")
    with open(txt_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(to_netscape(cookies))
    with open(os.path.join(COOKIE_DIR, host + ".json"), "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    with open(os.path.join(DATA_DIR, "latest.json"), "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    names = sorted({c.get("name", "") for c in cookies})
    log("[bridge] saved %d cookies for %s (SESSDATA=%s)"
        % (len(cookies), host, "SESSDATA" in names))
    return txt_path, host, len(cookies), names


def select_client(want=None):
    if want and want in clients:
        return clients[want]
    if not clients:
        return None
    if len(clients) == 1:
        return next(iter(clients.values()))
    # 多個時挑最後連線的
    return sorted(clients.values(), key=lambda c: c.connected)[-1]


def trim_dir(path, max_files=200, max_bytes=512 * 1024 * 1024, ext=".png"):
    """避免截圖／PDF 無限累積：超過張數或總大小就刪最舊的。"""
    try:
        if not os.path.isdir(path):
            return
        files = [
            os.path.join(path, f)
            for f in os.listdir(path)
            if f.lower().endswith(ext)
        ]
        files.sort(key=lambda p: os.path.getmtime(p))
        total = 0
        for p in files:
            try:
                total += os.path.getsize(p)
            except Exception:
                pass
        while files and (len(files) > max_files or total > max_bytes):
            oldest = files.pop(0)
            try:
                total -= os.path.getsize(oldest)
            except Exception:
                pass
            try:
                os.remove(oldest)
            except Exception:
                pass
    except Exception:
        pass


def maybe_save_shot(method, data):
    if not isinstance(data, dict):
        return data
    url = data.get("dataUrl")
    if not url:
        return data
    try:
        b64 = url.split(",", 1)[-1]
        raw = base64.b64decode(b64)
        os.makedirs(SHOT_DIR, exist_ok=True)
        name = "shot-%s.png" % time.strftime("%Y%m%d-%H%M%S")
        path = os.path.join(SHOT_DIR, name)
        with open(path, "wb") as f:
            f.write(raw)
        data = dict(data)
        data.pop("dataUrl", None)
        data["path"] = path
        data["bytes"] = len(raw)
        trim_dir(SHOT_DIR, max_files=200)
    except Exception as e:
        log("[bridge] screenshot save failed: %s" % e)
    return data


# ---------------- WebSocket ----------------

async def on_ws_message(client: Client, data: dict):
    t = data.get("type")
    if t == "hello":
        client.id = data.get("clientId") or uuid.uuid4().hex
        client.version = data.get("version") or ""
        client.control = bool(data.get("control"))
        client.active = data.get("activeTab") or {}
        clients[client.id] = client
        log("[bridge] browser connected: %s v%s control=%s"
            % (client.id, client.version, client.control))
        await client.ws.send_json({"type": "welcome", "clientId": client.id})
        return

    if t == "ping":
        await client.ws.send_json({"type": "pong"})
        return

    if t == "state":
        client.control = bool(data.get("control"))
        if data.get("activeTab"):
            client.active = data.get("activeTab")
        return

    if t == "result":
        cid = data.get("id")
        item = pending.get(cid)
        if not item:
            return
        fut, _ = item
        if not fut.done():
            fut.set_result(data)
        return


async def ws_handler(request):
    ws = web.WebSocketResponse(heartbeat=20, max_msg_size=0)
    await ws.prepare(request)
    client = Client(ws)
    try:
        async for msg in ws:
            if msg.type == WSMsgType.TEXT:
                try:
                    data = json.loads(msg.data)
                except Exception:
                    continue
                await on_ws_message(client, data)
            elif msg.type == WSMsgType.ERROR:
                break
    finally:
        if client.id:
            clients.pop(client.id, None)
            log("[bridge] browser disconnected: %s" % client.id)
        # 讓等待中的指令立即失敗
        for cid, (fut, cid_owner) in list(pending.items()):
            if cid_owner == client.id and not fut.done():
                fut.set_exception(RuntimeError("browser disconnected"))
    return ws


# ---------------- HTTP handlers ----------------

async def health(request):
    return web.json_response(
        {
            "status": "ok",
            "time": time.time(),
            "version": "2.0",
            "clients": [c.summary() for c in clients.values()],
            "pending": len(pending),
        }
    )


async def list_clients(request):
    return web.json_response({"clients": [c.summary() for c in clients.values()]})


async def cmd_handler(request):
    try:
        body = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)

    method = body.get("method")
    if not method:
        return web.json_response({"ok": False, "error": "method required"}, status=400)
    args = body.get("args") or {}
    timeout = float(body.get("timeout") or 25)
    client = select_client(body.get("client"))
    if not client:
        return web.json_response(
            {"ok": False, "error": "no browser client connected"}, status=503
        )

    cid = uuid.uuid4().hex
    fut = asyncio.get_running_loop().create_future()
    pending[cid] = (fut, client.id)
    started = time.time()
    try:
        await client.ws.send_json({"type": "cmd", "id": cid, "method": method, "args": args})
    except Exception as e:
        pending.pop(cid, None)
        return web.json_response({"ok": False, "error": "send failed: %s" % e}, status=502)

    try:
        result = await asyncio.wait_for(fut, timeout=timeout)
    except asyncio.TimeoutError:
        return web.json_response(
            {"ok": False, "error": "timeout after %.0fs" % timeout, "method": method},
            status=504,
        )
    except Exception as e:
        return web.json_response({"ok": False, "error": str(e)}, status=502)
    finally:
        pending.pop(cid, None)

    elapsed = round((time.time() - started) * 1000)
    if result.get("ok"):
        data = maybe_save_shot(method, result.get("data"))
        return web.json_response(
            {"ok": True, "method": method, "data": data,
             "client": client.id, "ms": elapsed}
        )
    return web.json_response(
        {"ok": False, "method": method, "error": result.get("error"),
         "client": client.id, "ms": elapsed}
    )


INBOX_PATH = os.path.join(DATA_DIR, "inbox.json")


def load_inbox():
    try:
        with open(INBOX_PATH, encoding="utf-8") as f:
            data = json.load(f)
        return data if isinstance(data, list) else []
    except Exception:
        return []


def save_inbox(items):
    os.makedirs(DATA_DIR, exist_ok=True)
    tmp = INBOX_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)
    os.replace(tmp, INBOX_PATH)


async def post_inbox(request):
    """擴充把「選取文字 / 頁面 / 連結」丟進來，agent 之後用 GET /inbox 領取。"""
    try:
        payload = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    items = load_inbox()
    item = dict(payload)
    item.setdefault("id", uuid.uuid4().hex)
    item.setdefault("ts", time.time())
    items.append(item)
    items = items[-200:]
    save_inbox(items)
    log("[bridge] inbox +1 (%s) total=%d" % (item.get("kind") or item.get("source") or "item", len(items)))
    return web.json_response({"ok": True, "id": item["id"], "count": len(items)})


async def get_inbox(request):
    items = load_inbox()
    try:
        limit = int(request.query.get("limit") or 50)
    except Exception:
        limit = 50
    return web.json_response({"ok": True, "count": len(items), "items": items[-max(1, limit):]})


async def delete_inbox(request):
    save_inbox([])
    return web.json_response({"ok": True, "count": 0})


async def post_cookies(request):
    try:
        payload = await request.json()
    except Exception:
        return web.json_response({"ok": False, "error": "bad json"}, status=400)
    cookies = payload.get("cookies")
    if not isinstance(cookies, list) or not cookies:
        return web.json_response(
            {"ok": False, "error": "cookies must be a non-empty list"}, status=400
        )
    txt, host, count, names = save_cookies(payload)
    return web.json_response(
        {"ok": True, "count": count, "host": host, "saved": txt, "names": names[:40]}
    )


async def get_cookies(request):
    host = safe_name(request.match_info["host"])
    q = request.query.get("format")
    if q == "json":
        p = os.path.join(COOKIE_DIR, host + ".json")
        if not os.path.exists(p):
            return web.json_response({"error": "not found", "host": host}, status=404)
        return web.json_response(json.load(open(p, encoding="utf-8")))
    p = os.path.join(COOKIE_DIR, host + ".txt")
    if not os.path.exists(p):
        return web.json_response({"error": "not found", "host": host}, status=404)
    return web.Response(text=open(p, encoding="utf-8").read(),
                        content_type="text/plain", charset="utf-8")


async def get_domains(request):
    names = []
    if os.path.isdir(COOKIE_DIR):
        names = sorted(f[:-4] for f in os.listdir(COOKIE_DIR) if f.endswith(".txt"))
    return web.json_response({"domains": names})


async def get_shot(request):
    name = request.match_info["name"]
    if not re.fullmatch(r"[A-Za-z0-9._-]+\.png", name):
        return web.json_response({"error": "bad name"}, status=400)
    p = os.path.join(SHOT_DIR, name)
    if not os.path.exists(p):
        return web.json_response({"error": "not found"}, status=404)
    return web.FileResponse(p)


# ---------------- app ----------------

@web.middleware
async def cors_middleware(request, handler):
    if request.method == "OPTIONS":
        return web.Response(status=204, headers=CORS)
    resp = await handler(request)
    for k, v in CORS.items():
        resp.headers[k] = v
    return resp


def build_app():
    app = web.Application(middlewares=[cors_middleware])
    app.router.add_get("/health", health)
    app.router.add_get("/clients", list_clients)
    app.router.add_post("/cmd", cmd_handler)
    app.router.add_post("/inbox", post_inbox)
    app.router.add_get("/inbox", get_inbox)
    app.router.add_delete("/inbox", delete_inbox)
    app.router.add_post("/cookies", post_cookies)
    app.router.add_get("/cookies/{host}", get_cookies)
    app.router.add_get("/domains", get_domains)
    app.router.add_get("/screenshots/{name}", get_shot)
    app.router.add_get("/ws", ws_handler)
    return app


def main():
    global LOG_PATH
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="127.0.0.1")
    ap.add_argument("--port", type=int, default=8765)
    ap.add_argument("--log-file", default=os.path.join(DATA_DIR, "bridge.log"),
                    help="常駐時的日誌檔（給排程/背景啟動用）")
    ap.add_argument("--no-log-file", action="store_true")
    args = ap.parse_args()

    configure_stdio()
    LOG_PATH = None if args.no_log_file else args.log_file
    trim_log()

    os.makedirs(COOKIE_DIR, exist_ok=True)
    os.makedirs(SHOT_DIR, exist_ok=True)
    log("[bridge] v2 listening on http://%s:%d  (ws: /ws)" % (args.host, args.port))
    log("[bridge] data dir: %s" % DATA_DIR)
    web.run_app(build_app(), host=args.host, port=args.port, print=None)


if __name__ == "__main__":
    main()
